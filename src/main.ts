function setSongsOpen(open: boolean): void {
  app.classList.toggle('songs-open', open);
  songsButton.setAttribute('aria-expanded', String(open));
}

function bindSongsDrawer(): void {
  songsButton.addEventListener('click', () => setSongsOpen(!app.classList.contains('songs-open')));
  el('songs-backdrop').addEventListener('click', () => setSongsOpen(false));
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') setSongsOpen(false);
  });
}

function loadSong(song: Song): void {
  const lines = parseSong(song.text);
  if (lines.length === 0) {
    showStatus(`No hole numbers found in ${song.name}.`);
    return;
  }
  showStatus('');
  activeSong = song.name;
  items = songToItems(lines);
  redrawStaff('top');
  renderSongList();
}

function deleteSong(song: Song): void {
  if (!confirm(`Delete ${song.name}?`)) return;
  songs.splice(songs.indexOf(song), 1);
  if (activeSong === song.name) {
    activeSong = null; // the staff keeps showing it until something else is loaded
  }
  renderSongList();
  void store(song.name, (library) => library.deleteSong(song.name));
}

async function importFiles(files: File[]): Promise<void> {
  const added: Song[] = [];
  for (const file of files) {
    try {
      added.push({ name: file.name, text: await file.text() });
    } catch (e) {
      showStatus(`Could not read ${file.name}: ${e instanceof Error ? e.message : e}`);
    }
  }
  for (const song of added) {
    const existing = songs.findIndex((s) => s.name === song.name);
    if (existing >= 0) {
      songs[existing] = song;
    } else {
      songs.push(song);
    }
  }
  sortSongs();
  renderSongList();
  const last = added.at(-1);
  if (last) {
    loadSong(last);
  }
  if (added.length > 0) {
    void store(added.length === 1 ? last!.name : `${added.length} songs`, (library) => library.saveSongs(added));
  }
}

/** Reads back saved songs and recordings. Anything imported or recorded meanwhile wins. */
async function loadLibrary(): Promise<void> {
  const library = await libraryReady;
  if (!library) return;
  try {
    const [savedSongs, savedRecordings] = await Promise.all([library.songs(), library.recordings()]);
    songs.push(...savedSongs.filter((saved) => !songs.some((s) => s.name === saved.name)));
    sortSongs();
    recordings.restore(savedRecordings);
  } catch (e) {
    showStatus(`Could not load saved songs and recordings: ${e instanceof Error ? e.message : e}`);
    return;
  }
  renderSongList();
  renderRecordings();
}

function setToggle(button: HTMLElement, on: boolean): void {
  button.setAttribute('aria-pressed', String(on));
}

function bindToggle(id: string, field: 'showHoles' | 'showLetters'): void {
  const button = el(id);
  setToggle(button, settings[field]);
  button.addEventListener('click', () => {
    persist({ [field]: !settings[field] });
    setToggle(button, settings[field]);
    staff.setOptions(settings);
  });
}

const sliders = [
  { field: 'spacing', format: (v: number) => String(v) },
  { field: 'noteScale', format: (v: number) => `${v.toFixed(1)}x` },
  { field: 'annotationSize', format: (v: number) => String(v) },
] as const;

function syncSettingsForm(): void {
  el<HTMLSelectElement>('key-select').value = settings.keyName;
  for (const { field, format } of sliders) {
    el<HTMLInputElement>(`${field}-input`).value = String(settings[field]);
    el(`${field}-value`).textContent = format(settings[field]);
  }
}

function bindSettings(): void {
  const keySelect = el<HTMLSelectElement>('key-select');
  keySelect.append(...HARMONICA_KEYS.map((k) => new Option(k.name, k.name)));
  keySelect.addEventListener('change', () => setKey(keySelect.value));

  for (const { field, format } of sliders) {
    const input = el<HTMLInputElement>(`${field}-input`);
    input.min = String(LIMITS[field].min);
    input.max = String(LIMITS[field].max);
    input.addEventListener('input', () => {
      persist({ [field]: Number(input.value) });
      el(`${field}-value`).textContent = format(settings[field]);
      staff.setOptions(settings);
    });
  }

  el('settings-default').addEventListener('click', () => {
    const { spacing, noteScale, annotationSize, keyName } = DEFAULT_SETTINGS;
    persist({ spacing, noteScale, annotationSize });
    setKey(keyName);
    staff.setOptions(settings);
    syncSettingsForm();
  });
  syncSettingsForm();
}

function setKey(keyName: string): void {
  persist({ keyName });
  harmonica = new Harmonica(keyByName(keyName)!);
  redrawStaff('keep');
}

function setSidebarWidth(width: number): void {
  const { min, max } = LIMITS.sidebarWidth;
  const limit = Math.min(max, window.innerWidth / 2);
  const clamped = Math.round(Math.min(limit, Math.max(min, width)));
  document.documentElement.style.setProperty('--sidebar-width', `${clamped}px`);
  persist({ sidebarWidth: clamped });
}

function bindSplitter(): void {
  const splitter = el('splitter');
  splitter.addEventListener('pointerdown', (event) => {
    splitter.setPointerCapture(event.pointerId);
  });
  splitter.addEventListener('pointermove', (event) => {
    if (splitter.hasPointerCapture(event.pointerId)) {
      setSidebarWidth(event.clientX);
    }
  });
  splitter.addEventListener('keydown', (event) => {
    const delta = { ArrowLeft: -20, ArrowRight: 20 }[event.key];
    if (delta) {
      event.preventDefault();
      setSidebarWidth(settings.sidebarWidth + delta);
    }
  });
  document.documentElement.style.setProperty('--sidebar-width', `${settings.sidebarWidth}px`);
}

/** Maps an RMS level onto a 60 dB meter, since loudness is heard logarithmically. */
function levelPercent(rms: number): number {
  const db = 20 * Math.log10(Math.max(rms, 1e-6));
  return Math.min(100, Math.max(0, ((db + 60) / 60) * 100));
}

let mic: MicSession | null = null;
// The last few recordings, saved from Settings so a misread note can be sent in as a test case.
const recordings = new RecordingList(3, RECORDING_MAX_SECONDS);
let currentRecording: Recording | null = null;
const recordingList = el<HTMLUListElement>('recording-list');

function formatDuration(seconds: number): string {
  const s = Math.round(seconds);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}

function renderRecordings(): void {
  recordingList.replaceChildren(
    ...recordings.all.map((recording) => {
      const time = recording.startedAt.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
      const length = recording === currentRecording ? 'recording…' : formatDuration(recording.duration);
      const label = document.createElement('span');
      label.textContent = `${time} · ${length} · ${recording.keyName} harp`;
      const save = document.createElement('button');
      save.type = 'button';
      save.textContent = 'Save';
      save.title = 'Save as a WAV file';
      save.addEventListener('click', () => void saveRecording(recording));
      const row = document.createElement('li');
      row.append(label, save);
      return row;
    }),
  );
  el('recording-empty').hidden = recordings.all.length > 0;
}

function fileStamp(date: Date): string {
  return date.toISOString().slice(0, 19).replace(/[T:]/g, '-');
}

async function saveRecording(recording: Recording): Promise<void> {
  const file = new File([recording.toWav()], `harmonica-${recording.keyName}-${fileStamp(recording.startedAt)}.wav`, {
    type: 'audio/wav',
  });
  await saveFile(file);
}

/** Saves what's on the staff as a tab file Import can read back. */
async function exportTab(): Promise<void> {
  const now = new Date();
  const base = activeSong ? activeSong.replace(/\.txt$/i, '') : `harmonica-tab-${harmonica.key.name}`;
  const title = `${activeSong ?? 'Harmonica tab'}, exported for a ${harmonica.key.name} harp on ${now.toLocaleString()}`;
  const file = new File([staffToTab(items, title)], `${base}-${fileStamp(now)}.txt`, { type: 'text/plain' });
  await saveFile(file);
}

async function saveFile(file: File): Promise<void> {
  // On phones, the share sheet can send the file straight to a chat or Drive.
  if (navigator.canShare?.({ files: [file] })) {
    try {
      await navigator.share({ files: [file], title: file.name });
      return;
    } catch (e) {
      if (e instanceof DOMException && e.name === 'AbortError') return; // closed the share sheet
    }
  }
  const url = URL.createObjectURL(file);
  const link = document.createElement('a');
  link.href = url;
  link.download = file.name;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}
const recordButton = el<HTMLButtonElement>('record-button');
const levelMeter = el('level');
const levelFill = el('level-fill');

/** Stores the recording in progress, so it survives a reload or the phone closing the app. */
function storeRecording(recording: Recording): void {
  if (recording.duration === 0) return;
  void store('the recording', (library) => library.saveRecording(recording, recordings.all));
}

function stopRecording(): void {
  mic?.close();
  mic = null;
  if (currentRecording) {
    storeRecording(currentRecording);
  }
  currentRecording = null;
  renderRecordings();
  recordButton.textContent = 'Record';
  recordButton.disabled = false;
  levelMeter.hidden = true;
}

async function startRecording(): Promise<void> {
  recordButton.disabled = true;
  showStatus('');
  try {
    mic = await startListening({
      range: () => harmonica.range,
      onAudio(samples, sampleRate) {
        // Started on the first audio, so a mic that never opens leaves no empty recording behind.
        if (!currentRecording) {
          currentRecording = recordings.start(harmonica.key.name);
          renderRecordings();
        }
        currentRecording.push(samples, sampleRate);
      },
      onNotes(notes) {
        items.push({ kind: 'played', notes });
        redrawStaff('bottom');
      },
      onLevel(rms) {
        levelFill.style.width = `${levelPercent(rms)}%`;
      },
      onFailure(message) {
        stopRecording();
        showStatus(message);
      },
    });
  } catch (e) {
    stopRecording();
    showStatus(e instanceof MicError ? e.message : String(e));
    return;
  }
  showStatus(mic.warning ?? '');
  recordButton.textContent = 'Stop';
  recordButton.disabled = false;
  levelMeter.hidden = false;
}

recordButton.addEventListener('click', () => {
  if (mic) {
    stopRecording();
  } else {
    void startRecording();
  }
});
